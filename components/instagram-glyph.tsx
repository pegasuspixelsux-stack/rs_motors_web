/** Authored Instagram glyph — single-colour, inherits currentColor. Not in
 * lucide-react (brand icons were dropped from that package), so this mirrors
 * whatsapp-glyph.tsx's pattern instead of pulling in an icon library. */
export function InstagramGlyph({
  size = 16,
  className,
}: {
  size?: number;
  className?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      aria-hidden="true"
      className={className}
    >
      <rect x="3" y="3" width="18" height="18" rx="5" />
      <circle cx="12" cy="12" r="4.2" />
      <circle cx="17.4" cy="6.6" r="1.1" fill="currentColor" stroke="none" />
    </svg>
  );
}
